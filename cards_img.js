const CARD_IMG_VER = "1";
// 카드 종류로 판을 정한다: 음식·음료=가족판, 술·안주=회식판, 행동은 이름이 두 판에서 겹치지 않음
function cardEdition(c) {
if ("FD".includes(c.t)) return "family";
if ("SJ".includes(c.t)) return "hoesik";
return c.name in CARD_IMG.family ? "family" : "hoesik";
}
function cardImageUrl(c) {
const ed = cardEdition(c), id = CARD_IMG[ed][c.name];
return id ? `assets/ppung/${ed}/unique_cards/${id}.png?v=${CARD_IMG_VER}` : "";
}
