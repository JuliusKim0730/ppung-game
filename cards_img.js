// 카드 종류로 판을 정한다: 음식·음료=가족판, 술·안주=회식판, 행동은 이름이 두 판에서 겹치지 않음
function cardEdition(c) {
if ("FD".includes(c.t)) return "family";
if ("SJ".includes(c.t)) return "hoesik";
return c.name in CARD_IMG.family ? "family" : "hoesik";
}
// 카드 그림 정보: 이미지 경로, 아래 띠 색, 글자 색. 없으면 null
const CARD_INK = { family: { F: "#8e3a14", D: "#075a50", A: "#4f2b73", W: "#7e2039" }, hoesik: { S: "#6a3708", J: "#2a5121", A: "#281f49", W: "#6d1628" } };
function cardArt(c) {
const ed = cardEdition(c), e = CARD_IMG[ed][c.name];
if (!e) return null;
return { url: `assets/ppung/${ed}/unique_cards/${e[0]}.png?v=${CARD_IMG_VER}`, band: e[1], hd: ed === "family" ? 48 : 56, ink: CARD_INK[ed][c.t] || "#3b2a20" };
}
