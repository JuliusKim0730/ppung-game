// 판·종류별 카드 띠 색과 글자 색 (새 카드 시트 기준)
const CARD_TONE = {
family: { F: ["#f98f2b", "#8e3a14"], D: ["#36c69d", "#075a50"], A: ["#a467da", "#4f2b73"], W: ["#f0585a", "#7e2039"] },
hoesik: { S: ["#c06802", "#6a3708"], J: ["#2c7c01", "#22540a"], A: ["#5f2075", "#3b1150"], W: ["#c8202c", "#6d1628"] },
};
// 카드 종류로 판을 정한다: 음식·음료=가족판, 술·안주=회식판, 행동은 이름이 두 판에서 겹치지 않음
function cardEdition(c) {
if ("FD".includes(c.t)) return "family";
if ("SJ".includes(c.t)) return "hoesik";
return c.name in CARD_IMG.family ? "family" : "hoesik";
}
// 카드 그림 정보: 일러스트 경로, 띠 색, 글자 색, 배지. 없으면 null
function cardArt(c) {
const ed = cardEdition(c), e = CARD_IMG[ed][c.name];
if (!e) return null;
const [band, ink] = CARD_TONE[ed][c.t] || CARD_TONE[ed].A;
return { url: `assets/ppung/${ed}/art/${e[0]}.webp?v=${CARD_IMG_VER}`, band, ink, badge: e[1] || "", quote: e[2] || "" };
}
// 이미지 로드 실패: 이미지만 걷어내고 밑에 깔린 종이 카드를 보여 준다
function cardImgFail(img) { const b = img.closest(".card"); if (b) b.classList.remove("image-card"); img.remove(); }
